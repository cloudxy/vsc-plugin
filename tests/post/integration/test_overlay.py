"""Real independent PG plate selection survives freeze/export/scaffolding."""
import copy
import hashlib
import importlib.util
import io
import json
import os
from pathlib import Path
import tempfile
import unittest
from PIL import Image, ImageDraw
from support.fixtures.resource_store import ResourceStoreFixture
from vsc.assets.resource_service import ResourceError
from vsc.post.resource_export import export_render_package, scaffold_render_package
from vsc.production.performance import execution_problems


@unittest.skipUnless(os.environ.get('VSC_TEST_DATABASE_URL') and importlib.util.find_spec('psycopg'), 'requires existing isolated PG')
class OverlayPGTest(ResourceStoreFixture, unittest.TestCase):
    def setUp(self):
        super().setUp()
        from vsc.adapters.storage.local.store import LocalStorage
        self.temp = tempfile.TemporaryDirectory(); self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name); self.service.storage = LocalStorage(self.root / 'storage')
        self.objects = self.hierarchy()
        self.parameters = {key: 'Synthetic fixture: ' + key for key in ('purpose','acceptance','fallback','trigger','world_rule','trajectory','contact','occlusion','light_response','environment_response','aftereffects','sound')}
        self.parameters.update(route='composite', purpose='A transparent red square moves over the owned base; numeric technical fixture',
            trajectory='ease_in from pixel20,20 to220,80 over25 frames; fixed64x48 rectangle', sound='No sound generated by this plate')
        self.parameters['layers'] = [
            {'name': 'owned base image', 'purpose': 'full-frame synthetic background', 'occlusion': 'behind plate'},
            {'name': 'independent transparent plate', 'purpose': 'owned compositing input', 'occlusion': 'RGBA outside rectangle remains transparent'}]
        self.assertEqual(execution_problems('vfx', self.parameters), [])
        self.spec = self.write('create_artifact', {'artifact_key': 'vfx-spec', 'artifact_type': 'vfx-spec',
            'document': {'domain': 'vfx', 'parameters': self.parameters}, 'object_ids': [self.objects['shot']]})
        self.write('decide_artifact', {'artifact_id': self.spec['id'], 'reason': 'Synthetic fixture decision only'})
        self.base = self.register_image('base', (30, 70, 110, 255), False)
        self.plate = self.register_image('plate', (255, 0, 0, 255), True)
        self.base_decision = self.select(self.candidate(self.objects['shot'], self.base['id'], role='first_frame'))
        self.plate_decision = self.select(self.candidate(self.objects['shot'], self.plate['id'], role='vfx_overlay'))

    def register_image(self, name, color, transparent):
        image = Image.new('RGBA', (64, 48), (0,0,0,0) if transparent else color)
        if transparent: ImageDraw.Draw(image).rectangle((8,8,55,39), fill=color)
        stream = io.BytesIO(); image.save(stream, format='PNG'); stream.seek(0)
        staged = self.service.storage.stage_upload(stream, name + '.png')
        media = self.write('register_media', {'name': name, 'staged_upload': staged['staged_upload'], 'rights': 'owned',
            'rights_scope': {'purposes': ['*']}, 'source': {'kind': 'synthetic-owned', 'content': 'Generated geometric fixture under fixed VFX specification ' + self.spec['sha256']}})
        self.write('record_media_check', {'media_id': media['id'], 'checker': 'fixture-decoded-PNG', 'criteria_version': '1', 'outcome': 'pass'})
        return self.service.get_media(self.p, media['id'])

    def documents(self):
        selected = {'format':'vsc.selected-takes/v1','project_id':self.p,'scope':'EPISODE','items':[]}
        for key, media, purpose in [('base',self.base,'visual'),('plate',self.plate,'vfx_overlay')]:
            selected['items'].append({'id':key,'shot_id':'SHOT','take_id':'TAKE-'+key,'output_id':'OUT-'+key,'scope':'EPISODE',
                'purpose':purpose,'usage_rights':'owned','selected_by':'synthetic-fixture',
                'media':{'path':key+'.png','sha256':media['sha256']},'source':{'kind':'manual',
                    'artifact':{'id':self.spec['id'],'sha256':self.spec['sha256']},'imported_by':'synthetic-fixture','provenance':'Owned geometry generated from the fixed specification'}})
        selection = self.write('create_artifact', {'artifact_key':'selected','artifact_type':'vsc.selected_takes','document':selected,'dependency_ids':[self.spec['id']]})
        self.write('decide_artifact', {'artifact_id':selection['id'],'reason':'Synthetic separate base and plate selection'})
        plan = {'format':'vsc.remotion-render-plan/v1','project_id':self.p,
            'composition':{'id':'Overlay','width':320,'height':240,'fps':25,'duration_in_frames':50},'segments':[
                {'id':'base','kind':'image','source':'base.png','source_shot_id':'SHOT','from_frame':0,'duration_in_frames':50},
                {'id':'plate','kind':'image','source':'plate.png','source_shot_id':'SHOT','source_sha256':self.plate['sha256'],
                    'from_frame':10,'duration_in_frames':25,'overlay':{'x':20,'y':20,'width':64,'height':48,'alpha':.5,'layer':1,'blend_mode':'normal',
                        'motion':{'to':{'x':220,'y':80},'easing':'ease_in'}}}]}
        document = {'format':'vsc.timeline/v1','project_id':self.p,'scope':'EPISODE',
            'selected_takes':{'id':selection['id'],'sha256':selection['sha256']},'sound_plans':[],'render_plan':plan,
            'bindings':[{'segment_id':key,'selected_item_id':key,'sha256':media['sha256'],'purpose':purpose,'usage_rights':'owned','audio_role':'none','cue_id':None}
                for key,media,purpose in [('base',self.base,'visual'),('plate',self.plate,'vfx_overlay')]]}
        mappings = {key:{'media_id':media['id'],'binding_decision_id':decision['decision_id']}
            for key,media,decision in [('base',self.base,self.base_decision),('plate',self.plate,self.plate_decision)]}
        return document,selection,mappings

    def timeline(self, document, selection):
        artifact = self.write('create_artifact', {'artifact_key':'timeline','artifact_type':'vsc.timeline','document':document,'dependency_ids':[selection['id']]})
        self.write('decide_artifact', {'artifact_id':artifact['id'],'reason':'Synthetic composition decision'})
        return artifact

    def test_independent_plate_selection_freezes_and_original_export_keeps_bytes_geometry_and_provenance(self):
        document,selection,mappings = self.documents(); artifact = self.timeline(document,selection)
        wrong = copy.deepcopy(mappings); wrong['plate'] = mappings['base']
        with self.assertRaises(ResourceError): self.write('freeze_timeline', {'artifact_id':artifact['id'],'episode_id':self.objects['episode'],'selected_media':wrong})
        wrong_role = self.select(self.candidate(self.objects['shot'], self.plate['id'], role='composition', slot_key='wrong-purpose'))
        wrong = copy.deepcopy(mappings); wrong['plate']['binding_decision_id'] = wrong_role['decision_id']
        with self.assertRaises(ResourceError) as rejected: self.write('freeze_timeline', {'artifact_id':artifact['id'],'episode_id':self.objects['episode'],'selected_media':wrong})
        self.assertEqual(rejected.exception.code,'overlay_selection_mismatch')
        other = self.write('create_object', {'kind':'shot','display_code':'SHOT-OTHER','parent_id':self.objects['sequence'],'ordinal':1})
        other_decision = self.select(self.candidate(other['id'],self.plate['id'],role='vfx_overlay'))
        wrong = copy.deepcopy(mappings); wrong['plate']['binding_decision_id'] = other_decision['decision_id']
        with self.assertRaises(ResourceError):
            self.write('freeze_timeline', {'artifact_id':artifact['id'],'episode_id':self.objects['episode'],'selected_media':wrong})
        invalid = copy.deepcopy(document); invalid['render_plan']['segments'][1]['overlay']['blend_mode'] = 'not-supported'
        legacy = self.write('create_artifact', {'artifact_key':'legacy-overlay','artifact_type':'edit-timeline','document':invalid,'dependency_ids':[selection['id']]})
        self.write('decide_artifact', {'artifact_id':legacy['id'],'reason':'Synthetic legacy alias boundary fixture'})
        with self.assertRaises(ResourceError) as rejected:
            self.write('freeze_timeline', {'artifact_id':legacy['id'],'episode_id':self.objects['episode'],'selected_media':mappings})
        self.assertEqual(rejected.exception.code,'invalid_render_plan')
        frozen = self.write('freeze_timeline', {'artifact_id':artifact['id'],'episode_id':self.objects['episode'],'selected_media':mappings})
        rows = self.store.get_timeline_media(self.p, frozen['id'])
        row = next(item for item in rows if item['role']=='vfx_overlay')
        self.assertEqual((row['media_id'],row['binding_decision_id'],row['blob_sha256']), (self.plate['id'],self.plate_decision['decision_id'],self.plate['sha256']))
        self.assertTrue(self.service.get_media_usage(self.p,self.plate['id'])['timeline_items'])
        target = Path(getattr(self,'evidence_root',self.root))
        target.mkdir(parents=True,exist_ok=True)
        export_render_package(self.service,self.p,frozen['id'],target/'package',formal_subtitles=False)
        scaffold_render_package(target/'package',target/'engine')
        exported = json.loads((target/'package/render-plan.json').read_text())
        plate = next(s for s in exported['segments'] if s['id']=='plate')
        self.assertEqual(plate['overlay'],document['render_plan']['segments'][1]['overlay'])
        self.assertEqual(hashlib.sha256((target/'engine/public'/plate['source']).read_bytes()).hexdigest(),self.plate['sha256'])
        (target/'fixed-facts.json').write_text(json.dumps({'specification':self.spec,'vfx_spec_document':{'domain':'vfx','parameters':self.parameters},'timeline':frozen,'timeline_media':rows,
            'plate_media':self.plate,'plate_decision':self.plate_decision,'source_plan':document,'synthetic_fixture_only':True},ensure_ascii=False,indent=2)+'\n')
        # A changed content-addressed plate cannot be exported under the old pin.
        path = self.service.storage.resolve(next(r['object_key'] for r in self.plate['locations'] if r['available']))
        path.write_bytes(path.read_bytes()+b'changed')
        with self.assertRaises(ResourceError): export_render_package(self.service,self.p,frozen['id'],target/'changed',formal_subtitles=False)
        self.assertFalse((target/'changed').exists())
